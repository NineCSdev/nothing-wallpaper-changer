package com.ninecsdev.wallpaperchanger.data.local

import androidx.room.Dao
import androidx.room.Delete
import androidx.room.Insert
import androidx.room.MapColumn
import androidx.room.OnConflictStrategy
import androidx.room.Query
import androidx.room.Transaction
import com.ninecsdev.wallpaperchanger.model.enums.CropRule
import com.ninecsdev.wallpaperchanger.model.CollectionRotationSetting
import com.ninecsdev.wallpaperchanger.model.enums.SourceType
import com.ninecsdev.wallpaperchanger.model.FolderExclusion
import com.ninecsdev.wallpaperchanger.model.Wallpaper
import com.ninecsdev.wallpaperchanger.model.WallpaperCollection
import com.ninecsdev.wallpaperchanger.model.WallpaperFile
import com.ninecsdev.wallpaperchanger.model.WallpaperImage
import kotlinx.coroutines.flow.Flow

/** Every query returning [WallpaperImage] builds on this so the column list cannot drift. */
private const val SELECT_WALLPAPER_IMAGES = """
    SELECT w.id, w.collectionId, w.fileId, f.uri, f.sourceType, f.isAvailable,
           w.editZoom, w.editOffsetX, w.editOffsetY, w.isManuallyAdded, w.addedAt, w.isDefault
    FROM wallpapers w JOIN wallpaper_files f ON w.fileId = f.id
"""

/**
 * Values per `IN (...)` statement: SQLite caps bind variables per statement (32766), so list-taking
 * methods split into runs of this length inside one transaction.
 */
private const val BIND_CHUNK_SIZE = 900

@Dao
abstract class WallpaperDao {

    // Ids are autogenerated, so a conflict means a caller invented an existing id: fail loudly rather than replace
    @Insert(onConflict = OnConflictStrategy.ABORT)
    abstract suspend fun insertCollection(collection: WallpaperCollection): Long

    // `IS NOT` rather than `!=`: a user-owned collection's appRole is NULL and `NULL != 'DEFAULTS'`
    // is NULL, which would filter out every collection the user made.
    @Query("SELECT * FROM collections WHERE appRole IS NOT 'DEFAULTS' ORDER BY lastUsedAt DESC")
    abstract fun observeAllCollections(): Flow<List<WallpaperCollection>>

    @Query("SELECT * FROM collections WHERE id = :collectionId LIMIT 1")
    abstract suspend fun getCollectionById(collectionId: Long): WallpaperCollection?

    @Query("SELECT * FROM collections WHERE isActive = 1 LIMIT 1")
    abstract suspend fun getActiveCollection(): WallpaperCollection?

    @Query("SELECT * FROM collections WHERE isActive = 1 LIMIT 1")
    abstract fun observeActiveCollection(): Flow<WallpaperCollection?>

    /** Two collections built from the same folder share one persisted grant, which may only be released when this reaches zero. */
    @Query("SELECT COUNT(*) FROM collections WHERE rootUri = :rootUri")
    abstract suspend fun countCollectionsWithRootUri(rootUri: String): Int

    @Query("SELECT rootUri FROM collections WHERE rootUri IS NOT NULL")
    abstract suspend fun getAllRootUris(): List<String>

    /** Null until the first favourite creates it. */
    @Query("SELECT * FROM collections WHERE appRole = 'FAVORITES' LIMIT 1")
    abstract suspend fun getFavoritesCollection(): WallpaperCollection?

    /** Null until it is created. */
    @Query("SELECT * FROM collections WHERE appRole = 'DEFAULTS' LIMIT 1")
    abstract suspend fun getDefaultsCollection(): WallpaperCollection?

    @Query("UPDATE collections SET name = :newName, defaultCropRule = :newRule, rotationPolicy = :newPolicy WHERE id = :collectionId")
    abstract suspend fun updateCollection(
        collectionId: Long,
        newName: String,
        newRule: CropRule,
        newPolicy: CollectionRotationSetting
    )

    /** Zeroing the change time lets the newly active collection pass the rotation gate on the next lock. */
    // TODO tests: see vault note tests/Collection Switch Rotation Gate Tests.md
    @Transaction
    open suspend fun setActiveCollection(collectionId: Long) {
        resetActiveCollection()
        markCollectionActive(collectionId)
        updateLastUsed(collectionId)
        updateLastWallpaperChangeAt(collectionId, 0L)
    }

    @Query("UPDATE collections SET isPinned = :pinned WHERE id = :collectionId")
    abstract suspend fun setCollectionPinned(collectionId: Long, pinned: Boolean)

    @Query("UPDATE collections SET lastWallpaperChangeAt = :timestamp WHERE id = :collectionId")
    abstract suspend fun updateLastWallpaperChangeAt(collectionId: Long, timestamp: Long = System.currentTimeMillis())

    @Delete
    abstract suspend fun deleteCollection(collection: WallpaperCollection)

    @Query("UPDATE collections SET isActive = 0")
    abstract suspend fun resetActiveCollection()

    @Query("UPDATE collections SET isActive = 1 WHERE id = :collectionId")
    abstract suspend fun markCollectionActive(collectionId: Long)

    @Query("UPDATE collections SET lastUsedAt = :timestamp WHERE id = :collectionId")
    abstract suspend fun updateLastUsed(collectionId: Long, timestamp: Long = System.currentTimeMillis())

    /** Returns -1 on a `uri` conflict; use [getOrCreateFile]. */
    @Insert(onConflict = OnConflictStrategy.IGNORE)
    abstract suspend fun insertFile(file: WallpaperFile): Long

    @Query("SELECT * FROM wallpaper_files WHERE uri = :uri LIMIT 1")
    abstract suspend fun getFileByUri(uri: String): WallpaperFile?

    /**
     * A reused row is also restored to available: the source was just proven readable (picker probe
     * or folder scan), so a stale self-heal flag must not keep excluding it from rotation.
     */
    @Transaction
    open suspend fun getOrCreateFile(uri: String, sourceType: SourceType, addedAt: Long): Long {
        val inserted = insertFile(WallpaperFile(uriString = uri, sourceType = sourceType, addedAt = addedAt))
        if (inserted != -1L) return inserted
        val existing = getFileByUri(uri)!!
        if (!existing.isAvailable || !existing.isVerified) markFileRelinked(existing.id)
        return existing.id
    }

    @Query("SELECT * FROM wallpaper_files WHERE id NOT IN (SELECT DISTINCT fileId FROM wallpapers)")
    abstract suspend fun getOrphanFiles(): List<WallpaperFile>

    @Query("SELECT id FROM wallpaper_files")
    abstract suspend fun getAllFileIds(): List<Long>

    @Query("SELECT uri FROM wallpaper_files WHERE sourceType = :type")
    abstract suspend fun getFileUrisBySourceType(type: SourceType): List<String>

    @Query("SELECT * FROM wallpaper_files WHERE sourceType = :type")
    abstract suspend fun getFilesBySourceType(type: SourceType): List<WallpaperFile>

    @Query("SELECT COUNT(*) FROM wallpaper_files WHERE sourceType = :type")
    abstract fun observeFileCountBySourceType(type: SourceType): Flow<Int>

    @Query("UPDATE wallpaper_files SET isAvailable = :available WHERE id = :fileId")
    abstract suspend fun setFileAvailability(fileId: Long, available: Boolean)

    @Transaction
    open suspend fun setFilesAvailability(fileIds: List<Long>, available: Boolean) {
        fileIds.chunked(BIND_CHUNK_SIZE).forEach { setFilesAvailabilityChunk(it, available) }
    }

    @Query("UPDATE wallpaper_files SET isAvailable = :available WHERE id IN (:fileIds)")
    protected abstract suspend fun setFilesAvailabilityChunk(fileIds: List<Long>, available: Boolean)

    /** Re-links an unavailable image keeping its edit params. The caller must ensure [uri] is not held by another file row (uri is unique). */
    @Query("UPDATE wallpaper_files SET uri = :uri, sourceType = :sourceType, isAvailable = 1, isVerified = 1 WHERE id = :fileId")
    abstract suspend fun rebindFile(fileId: Long, uri: String, sourceType: SourceType)

    @Query("UPDATE wallpaper_files SET isVerified = :verified WHERE id = :fileId")
    abstract suspend fun setFileVerified(fileId: Long, verified: Boolean)

    /** Clears both self-heal flags at once, for a file whose source the user has just picked. */
    @Query("UPDATE wallpaper_files SET isAvailable = 1, isVerified = 1 WHERE id = :fileId")
    abstract suspend fun markFileRelinked(fileId: Long)

    /**
     * Re-link merge step: drops the old file's join rows in collections that already reference [newFileId], so
     * [repointJoinRows] cannot violate the unique (collectionId, fileId) index. The pre-existing membership wins.
     */
    @Query("DELETE FROM wallpapers WHERE fileId = :oldFileId AND collectionId IN (SELECT collectionId FROM wallpapers WHERE fileId = :newFileId)")
    abstract suspend fun deleteJoinRowsDuplicatedByMerge(oldFileId: Long, newFileId: Long)

    @Query("UPDATE wallpapers SET fileId = :newFileId WHERE fileId = :oldFileId")
    abstract suspend fun repointJoinRows(oldFileId: Long, newFileId: Long)

    @Transaction
    open suspend fun deleteFilesByIds(ids: List<Long>) {
        ids.chunked(BIND_CHUNK_SIZE).forEach { deleteFilesByIdsChunk(it) }
    }

    @Query("DELETE FROM wallpaper_files WHERE id IN (:ids)")
    protected abstract suspend fun deleteFilesByIdsChunk(ids: List<Long>)

    // An insert binds one row at a time, so the cap behind BIND_CHUNK_SIZE does not reach this path.
    @Insert(onConflict = OnConflictStrategy.IGNORE)
    abstract suspend fun insertWallpapers(wallpapers: List<Wallpaper>)

    @Query("$SELECT_WALLPAPER_IMAGES WHERE w.collectionId = :collectionId AND w.isDefault = 0 ORDER BY w.addedAt DESC")
    abstract fun observeImagesForCollection(collectionId: Long): Flow<List<WallpaperImage>>

    /**
     * Every collection's oldest [limit] files, in rank order; a collection with no images is absent.
     * `ROW_NUMBER()` gives a per-collection top-N without a query per collection.
     */
    // TODO tests: see vault note tests/Collection Picker Tests.md
    @Query(
        """
        SELECT collectionId, fileId, uri, sourceType, isAvailable FROM (
            SELECT w.collectionId AS collectionId, f.id AS fileId, f.uri AS uri, f.sourceType AS sourceType, f.isAvailable AS isAvailable,
                   ROW_NUMBER() OVER (
                       PARTITION BY w.collectionId ORDER BY w.addedAt ASC, w.id ASC
                   ) AS rn
            FROM wallpapers w JOIN wallpaper_files f ON w.fileId = f.id
            WHERE w.isDefault = 0
        )
        WHERE rn <= :limit
        ORDER BY collectionId, rn
        """
    )
    abstract fun observePreviewFilesByCollection(limit: Int): Flow<Map<@MapColumn("collectionId") Long, List<PreviewFile>>>

    /** Collections with no images are absent, as in [observePreviewFilesByCollection]. */
    @Query("SELECT collectionId, COUNT(*) AS imageCount FROM wallpapers WHERE isDefault = 0 GROUP BY collectionId")
    abstract fun observeImageCountsByCollection(): Flow<Map<@MapColumn("collectionId") Long, @MapColumn("imageCount") Int>>

    /** Excludes unavailable files, so rotation never selects a source already known to be unreadable. */
    @Query("$SELECT_WALLPAPER_IMAGES WHERE w.collectionId = :collectionId AND w.isDefault = 0 AND f.isAvailable = 1")
    abstract fun observeAvailableImagesForCollection(collectionId: Long): Flow<List<WallpaperImage>>

    /** Candidates for a re-probe that may clear the flag if the file is readable again. */
    @Query("$SELECT_WALLPAPER_IMAGES WHERE w.collectionId = :collectionId AND f.isAvailable = 0")
    abstract suspend fun getUnavailableImagesForCollection(collectionId: Long): List<WallpaperImage>

    /** Folder sync diffs against these only, leaving manually added or re-linked images alone. */
    @Query("$SELECT_WALLPAPER_IMAGES WHERE w.collectionId = :collectionId AND w.isManuallyAdded = 0 AND f.sourceType = :sourceType")
    abstract suspend fun getFolderImagesForCollection(
        collectionId: Long,
        sourceType: SourceType = SourceType.FOLDER_DOC
    ): List<WallpaperImage>

    /** Lets cross-collection transfers detect files the target already holds. */
    @Transaction
    open suspend fun getWallpapersInCollectionForFiles(
        collectionId: Long,
        fileIds: List<Long>
    ): List<Wallpaper> =
        fileIds.chunked(BIND_CHUNK_SIZE).flatMap { getWallpapersInCollectionForFilesChunk(collectionId, it) }

    @Query("SELECT * FROM wallpapers WHERE collectionId = :collectionId AND isDefault = 0 AND fileId IN (:fileIds)")
    protected abstract suspend fun getWallpapersInCollectionForFilesChunk(
        collectionId: Long,
        fileIds: List<Long>
    ): List<Wallpaper>

    @Query("$SELECT_WALLPAPER_IMAGES WHERE w.id = :wallpaperId LIMIT 1")
    abstract suspend fun getWallpaperById(wallpaperId: Long): WallpaperImage?

    @Query("""
        UPDATE wallpapers
        SET editZoom = :zoom, editOffsetX = :offsetX, editOffsetY = :offsetY
        WHERE id = :wallpaperId
    """)
    abstract suspend fun updateWallpaperEdit(
        wallpaperId: Long,
        zoom: Float?,
        offsetX: Float?,
        offsetY: Float?
    )

    @Transaction
    open suspend fun deleteImagesByIds(ids: List<Long>) {
        ids.chunked(BIND_CHUNK_SIZE).forEach { deleteImagesByIdsChunk(it) }
    }

    @Query("DELETE FROM wallpapers WHERE id IN (:ids)")
    protected abstract suspend fun deleteImagesByIdsChunk(ids: List<Long>)

    // TODO tests: see vault note tests/Default Wallpaper Membership Tests.md (exclusion)

    /** The hidden flagged row of [collectionId]; only the app-owned defaults collection has one. */
    @Query("$SELECT_WALLPAPER_IMAGES WHERE w.collectionId = :collectionId AND w.isDefault = 1 LIMIT 1")
    abstract suspend fun getDefaultWallpaper(collectionId: Long): WallpaperImage?

    @Query("$SELECT_WALLPAPER_IMAGES JOIN collections c ON w.collectionId = c.id WHERE c.appRole = 'DEFAULTS' AND w.isDefault = 1 LIMIT 1")
    abstract fun observeGlobalDefaultWallpaper(): Flow<WallpaperImage?>

    /** Repoints a default row at a freshly picked file, dropping the edit that framed the old one. */
    @Query("UPDATE wallpapers SET fileId = :fileId, editZoom = NULL, editOffsetX = NULL, editOffsetY = NULL WHERE id = :wallpaperId")
    abstract suspend fun repointDefaultWallpaper(wallpaperId: Long, fileId: Long)

    /** Null follows the global default. */
    // TODO tests: see vault note tests/Default Wallpaper Membership Tests.md (per-collection override)
    @Query("UPDATE collections SET defaultWallpaperId = :wallpaperId WHERE id = :collectionId")
    abstract suspend fun setCollectionDefaultWallpaper(collectionId: Long, wallpaperId: Long?)

    /** Null when [collectionId] follows the global default. */
    @Query("$SELECT_WALLPAPER_IMAGES WHERE w.id = (SELECT defaultWallpaperId FROM collections WHERE id = :collectionId)")
    abstract suspend fun getCollectionDefaultWallpaper(collectionId: Long): WallpaperImage?

    @Query("$SELECT_WALLPAPER_IMAGES WHERE w.id = (SELECT defaultWallpaperId FROM collections WHERE id = :collectionId)")
    abstract fun observeCollectionDefaultWallpaper(collectionId: Long): Flow<WallpaperImage?>

    @Query("SELECT defaultWallpaperId FROM collections WHERE id = :collectionId")
    abstract fun observeCollectionDefaultWallpaperId(collectionId: Long): Flow<Long?>

    /** Files referenced only by default rows; the storage readout subtracts them because defaults are internalized regardless of "keep local copies". */
    @Query("""
        SELECT f.uri FROM wallpaper_files f
        WHERE f.id IN (SELECT fileId FROM wallpapers WHERE isDefault = 1)
          AND f.id NOT IN (SELECT fileId FROM wallpapers WHERE isDefault = 0)
    """)
    abstract suspend fun getDefaultOnlyFileUris(): List<String>

    @Query("SELECT DISTINCT w.fileId FROM wallpapers w JOIN collections c ON w.collectionId = c.id WHERE c.appRole = 'FAVORITES' AND w.isDefault = 0")
    abstract fun observeFavoriteFileIds(): Flow<List<Long>>

    @Transaction
    open suspend fun deleteJoinRowsForFiles(collectionId: Long, fileIds: List<Long>) {
        fileIds.chunked(BIND_CHUNK_SIZE).forEach { deleteJoinRowsForFilesChunk(collectionId, it) }
    }

    @Query("DELETE FROM wallpapers WHERE collectionId = :collectionId AND fileId IN (:fileIds)")
    protected abstract suspend fun deleteJoinRowsForFilesChunk(collectionId: Long, fileIds: List<Long>)

    /** IGNORE keeps the older row on a (collectionId, uri) conflict. */
    @Insert(onConflict = OnConflictStrategy.IGNORE)
    abstract suspend fun insertExclusions(exclusions: List<FolderExclusion>)

    @Query("SELECT * FROM folder_exclusions WHERE collectionId = :collectionId")
    abstract suspend fun getExclusionsForCollection(collectionId: Long): List<FolderExclusion>

    @Query("SELECT COUNT(*) FROM folder_exclusions WHERE collectionId = :collectionId")
    abstract fun observeExclusionCount(collectionId: Long): Flow<Int>

    @Query("DELETE FROM folder_exclusions WHERE collectionId = :collectionId")
    abstract suspend fun deleteExclusionsForCollection(collectionId: Long)

    @Query("SELECT * FROM folder_exclusions")
    abstract suspend fun getAllExclusions(): List<FolderExclusion>

    /** Add-path half of the invariant that a uri is never both excluded from and a member of the same collection. */
    @Transaction
    open suspend fun deleteExclusionsForUris(collectionId: Long, uris: List<String>) {
        uris.chunked(BIND_CHUNK_SIZE).forEach { deleteExclusionsForUrisChunk(collectionId, it) }
    }

    @Query("DELETE FROM folder_exclusions WHERE collectionId = :collectionId AND uri IN (:uris)")
    protected abstract suspend fun deleteExclusionsForUrisChunk(collectionId: Long, uris: List<String>)

    /** Including the defaults collection. */
    @Query("SELECT * FROM collections")
    abstract suspend fun getAllCollections(): List<WallpaperCollection>

    @Query("SELECT * FROM wallpaper_files")
    abstract suspend fun getAllFiles(): List<WallpaperFile>

    @Query("SELECT * FROM wallpapers")
    abstract suspend fun getAllWallpapers(): List<Wallpaper>

    /** Returns -1 when the collection already holds that file. */
    @Insert(onConflict = OnConflictStrategy.IGNORE)
    abstract suspend fun insertWallpaper(wallpaper: Wallpaper): Long

    /** Empties every table; the physical files the rows referenced stay on disk for the caller to handle. */
    @Transaction
    open suspend fun deleteEverything() {
        deleteAllWallpapers()
        deleteAllExclusions()
        deleteAllCollections()
        deleteAllFiles()
    }

    @Query("DELETE FROM wallpapers")
    protected abstract suspend fun deleteAllWallpapers()

    @Query("DELETE FROM folder_exclusions")
    protected abstract suspend fun deleteAllExclusions()

    @Query("DELETE FROM collections")
    protected abstract suspend fun deleteAllCollections()

    @Query("DELETE FROM wallpaper_files")
    protected abstract suspend fun deleteAllFiles()
}
